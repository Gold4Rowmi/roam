/// A Mac keycode as the Windows virtual key sent over the link.
pub fn to_vk(mac: u16) -> Option<u8> {
    if mac == 0x4C { return Some(0x0D) } // keypad Enter
    KEYS.iter().find(|k| k.0 == mac).map(|k| k.1)
}

/// A Windows virtual key as a Mac keycode. The side-less modifier codes count as the left key.
pub fn from_vk(vk: u8) -> Option<u16> {
    let vk = match vk { 0x10 => 0xA0, 0x11 => 0xA2, 0x12 => 0xA4, v => v };
    KEYS.iter().find(|k| k.1 == vk).map(|k| k.0)
}

/// Windows needs the extended flag on these, or arrows arrive as keypad digits.
pub fn extended(vk: u8) -> bool {
    matches!(vk, 0x21..=0x28 | 0x2D | 0x2E | 0x5B | 0x5C | 0x6F | 0xA3 | 0xA5)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_round_trips_and_codes_are_unique() {
        for (mac, vk) in KEYS {
            assert_eq!(to_vk(*mac), Some(*vk));
            assert_eq!(from_vk(*vk), Some(*mac));
        }
    }

    #[test]
    fn command_is_control_on_the_other_pc() {
        assert_eq!(to_vk(0x37), Some(0xA2)); // left Command sends left Control
        assert_eq!(from_vk(0xA2), Some(0x37));
        assert_eq!(from_vk(0x11), Some(0x37)); // the side-less code too
        assert_eq!(from_vk(0x5B), Some(0x3B)); // the Windows key is Control
        assert_eq!(to_vk(0x7F), None);
    }

    #[test]
    fn arrows_are_extended_and_letters_are_not() {
        assert!(extended(0x25) && extended(0x2E) && extended(0xA3));
        assert!(!extended(0x41) && !extended(0x0D));
    }
}
